create table users (
    id bigint generated by default as identity,
    email varchar(100) not null,
    password varchar(255) not null,
    nickname varchar(30) not null,
    phone_number varchar(20),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_users_email unique (email)
);

create table notices (
    id bigint generated by default as identity,
    bid_ntce_no varchar(40) not null,
    bid_ntce_ord varchar(3) not null,
    bid_ntce_nm varchar(1000) not null,
    ntce_instt_nm varchar(400) not null,
    dminstt_nm varchar(400),
    bid_type varchar(20) not null check (bid_type in ('GOODS', 'SERVICE', 'CONSTRUCTION', 'FOREIGN', 'ETC')),
    ntce_kind_nm varchar(100),
    re_ntce_yn varchar(1),
    bid_ntce_dt timestamp(6),
    bid_begin_dt timestamp(6),
    bid_clse_dt timestamp(6),
    openg_dt timestamp(6),
    rgst_dt timestamp(6) not null,
    chg_dt timestamp(6),
    bdgt_amt bigint,
    presmpt_prce bigint,
    cntrct_cncls_mthd_nm varchar(500),
    bid_methd_nm varchar(500),
    sucsfbid_mthd_cd varchar(9),
    sucsfbid_mthd_nm varchar(700),
    sucsfbid_mthd_app_std varchar(500),
    tech_ablt_evl_rt varchar(25),
    bid_prce_evl_rt varchar(25),
    bid_ntce_dtl_url varchar(512),
    std_ntce_doc_url varchar(800),
    ai_summary text,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_notices_bid_ntce_no_ord unique (bid_ntce_no, bid_ntce_ord)
);

create index idx_notices_bid_type on notices (bid_type);
create index idx_notices_bid_clse_dt on notices (bid_clse_dt);
create index idx_notices_bid_ntce_dt on notices (bid_ntce_dt);
create index idx_notices_ai_summary_std_doc_url on notices (ai_summary, std_ntce_doc_url);

create table notice_attachments (
    id bigint generated by default as identity,
    notice_id bigint not null,
    file_name varchar(300),
    file_url varchar(512) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_notice_attachments_notice_id foreign key (notice_id) references notices (id)
);

create table watchlist_items (
    id bigint generated by default as identity,
    user_id bigint not null,
    notice_id bigint not null,
    status varchar(255) not null check (status in ('REVIEWING', 'PREPARING', 'SUBMITTED', 'DROPPED')),
    memo varchar(1000),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_watchlist_items_user_id_notice_id unique (user_id, notice_id),
    constraint fk_watchlist_items_user_id foreign key (user_id) references users (id),
    constraint fk_watchlist_items_notice_id foreign key (notice_id) references notices (id)
);

create table checklist_items (
    id bigint generated by default as identity,
    watchlist_item_id bigint not null,
    title varchar(100) not null,
    checked boolean not null,
    sort_order integer not null,
    default_item boolean not null,
    checked_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_checklist_items_watchlist_item_id foreign key (watchlist_item_id) references watchlist_items (id)
);

create table notification_settings (
    id bigint generated by default as identity,
    user_id bigint not null,
    email_notification_enabled boolean not null,
    d3enabled boolean not null,
    d1enabled boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_notification_settings_user_id unique (user_id),
    constraint fk_notification_settings_user_id foreign key (user_id) references users (id)
);

create table notification_histories (
    id bigint generated by default as identity,
    user_id bigint not null,
    watchlist_item_id bigint not null,
    channel varchar(255) not null check (channel in ('EMAIL')),
    remaining_days integer not null,
    success boolean not null,
    error_message varchar(500),
    is_read boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_notification_histories_user_id foreign key (user_id) references users (id),
    constraint fk_notification_histories_watchlist_item_id foreign key (watchlist_item_id) references watchlist_items (id)
);
