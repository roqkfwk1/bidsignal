create table notice_change_notifications (
    id bigint generated by default as identity,
    user_id bigint not null,
    notice_id bigint not null,
    type varchar(20) not null check (type in ('CHANGED', 'CANCELED')),
    previous_bid_clse_dt timestamp(6),
    previous_openg_dt timestamp(6),
    status varchar(20) not null check (status in ('PENDING', 'SENDING', 'SENT', 'FAILED', 'SKIPPED')),
    retry_count integer not null default 0,
    error_message varchar(500),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_notice_change_notifications_user_id_notice_id unique (user_id, notice_id),
    constraint fk_notice_change_notifications_user_id foreign key (user_id) references users (id),
    constraint fk_notice_change_notifications_notice_id foreign key (notice_id) references notices (id)
);

create index idx_notice_change_notifications_status on notice_change_notifications (status);
